/**
 * 하루 단위로 거의 변동되지 않는 "안정" 데이터용 캐시 설정.
 * (주간/월간 태스크, 목표, 완료 기록(history), 채용 공고(jobs), D-day)
 *
 * 이 데이터들은 사용자의 편집을 통해서만 바뀌고, 편집 시 각 훅이
 * invalidateQueries / setQueryData 로 캐시를 즉시 갱신하므로 staleTime 을
 * 길게 두어도 수정 사항은 곧바로 반영된다. 그 외 메뉴를 옮겨 다니는 상황에서는
 * 24시간 동안 캐시된 내역을 그대로 보여줘 불필요한 재조회를 막는다.
 *
 * staleTime 만 늘리고 gcTime(기본 10분)을 그대로 두면, 해당 쿼리를 구독하는
 * 컴포넌트가 모두 언마운트된 뒤 10분이 지나면 캐시가 GC 로 제거되어 재조회된다.
 * 따라서 메뉴 이동 간 캐시 재사용 효과를 위해 gcTime 도 함께 늘린다.
 */
export const STABLE_QUERY_OPTIONS = {
  staleTime: 1000 * 60 * 60 * 24, // 24시간
  gcTime: 1000 * 60 * 60 * 24, // 24시간
} as const

/**
 * 일간(daily) 태스크용 캐시 설정.
 *
 * daily 는 편집 외에도 "시간 경과"로 내용이 바뀐다:
 *  - 하루 시작 시각(day_start_time) 게이트를 지나면 서버가 템플릿을 시딩한다.
 *  - 자정을 넘기면 조회 대상 날짜("오늘")가 달라진다.
 * 이런 변화는 뮤테이션 무효화로 커버되지 않으므로, 안정 데이터처럼 24시간씩
 * 캐시하면 새로 시딩된 템플릿/날짜 전환이 한참 동안 반영되지 않는다.
 * 따라서 staleTime 을 짧게 두어 게이트 통과·날짜 전환을 수 분 내에 반영하되,
 * 그 안에서 메뉴를 오갈 때는 캐시를 재사용한다.
 */
export const DAILY_QUERY_OPTIONS = {
  staleTime: 1000 * 60 * 5, // 5분
  gcTime: 1000 * 60 * 60, // 1시간
} as const
